CREATE TABLE audit_state(id INT PRIMARY KEY, last_hash CHAR(64) NOT NULL) ENGINE=InnoDB;
INSERT INTO audit_state VALUES(1,REPEAT('0',64));
CREATE TABLE audit_events (
 sequence_id BIGINT AUTO_INCREMENT PRIMARY KEY,event_id VARCHAR(36) NOT NULL UNIQUE,
 payload LONGTEXT NOT NULL,previous_hash CHAR(64) NOT NULL,event_hash CHAR(64) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
CREATE TRIGGER audit_no_update BEFORE UPDATE ON audit_events FOR EACH ROW SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Audit is immutable';
CREATE TRIGGER audit_no_delete BEFORE DELETE ON audit_events FOR EACH ROW SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Audit is immutable';
